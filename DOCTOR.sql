use Doctor

CREATE TABLE Client
(id_client INT PRIMARY KEY,
name_client nvarchar(15),
middle_name nvarchar(20),
tel char(10),
adress nvarchar(50))

CREATE TABLE Reservation
(id_reservation INT PRIMARY KEY,
date date,
hour_event time,
client_id INT FOREIGN KEY REFERENCES Client(id_client))


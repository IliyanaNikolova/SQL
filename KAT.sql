CREATE DATABASE KAT

use KAT

CREATE TABLE Drivers
(id_driver int PRIMARY KEY,
name_driver nvarchar(30),
surname_driver nvarchar(30),
adress nvarchar(30),
number_license char(9))

ALTER TABLE Drivers ADD  EGN CHAR(10)

CREATE TABLE Cars
(id_car int PRIMARY KEY,
reg_nomer char(4),
brand nvarchar(30),
model nvarchar(30),
color nvarchar(20),
year_made int)

CREATE TABLE Drivers_Cars
(driver_id int FOREIGN KEY REFERENCES Drivers(id_driver),
car_id int FOREIGN KEY REFERENCES Cars(id_car))

